/**
 * Keep the README's sample output honest.
 *
 * WHY THIS EXISTS
 * ---------------
 * The README shows what a ranked card and a refused call actually look like.
 * Both were originally transcribed by hand, and a hand-copied sample is a claim
 * about the code that nothing checks: the renderer can be reworded, the sample
 * keeps showing the old text, and the README then documents an output that no
 * longer exists. The card is the plugin's whole user-visible surface, so a stale
 * sample is not a cosmetic problem.
 *
 * So the samples are GENERATED from the shipped code and spliced between two
 * markers in each README. A README WITHOUT the markers has no sample to check
 * and is reported as `skipped`, never as `current` — the maintainer's edit
 * (m08551) removed the block from both READMEs, and a check that quietly passed
 * on a README it never examined would be worse than no check at all. The
 * generator is kept so that restoring the markers restores the guarantee:
 *
 *   - the ranked card comes from `renderRanked`, driven by a fixed three-repo
 *     pool, so the table, the declaration and the two counting lines are the
 *     renderer's own bytes;
 *   - the refused call comes from the REAL tool (`scout_projects.execute`)
 *     through the same fake context the test suite uses, so the refusal wording
 *     is the shipped wording rather than a paraphrase of it.
 *
 * `--check` re-generates and compares without writing, which is what makes the
 * markers enforceable rather than decorative. Run it after any change to
 * `src/render.ts` or the refusal path.
 *
 * Usage:
 *   node scripts/readme-sample.mjs           # regenerate both READMEs
 *   node scripts/readme-sample.mjs --check   # exit 1 when a sample is stale
 */

import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { fakeContext, loadPackageFile, loadPlugin, pkgRoot } from './script-env.mjs'

// Redirect the cache before the plugin is imported, so a documentation run can
// never read or write the developer's real cache. Same precaution as
// `test/plan-failure.test.mjs`; the refusal path returns before it touches the
// cache, but a future change must not be able to reach it from here.
process.env.DSH_HOME = mkdtempSync(join(tmpdir(), 'dsh-readme-'))

const START = '<!-- card-sample:start -->'
const END = '<!-- card-sample:end -->'
const PLACEHOLDER = '(placeholder — generated by scripts/readme-sample.mjs)'

