/** The idea that gets refused: Chinese, with no Latin keywords supplied. */
const REFUSED_IDEA = '一个本地优先的笔记应用'

/** The lead-in line above the refused sample, per README language. */
const REFUSAL_LEAD = {
  'README.md': '调用无法完成时，它同样返回一个值：',
  'README_EN.md': 'And when a call cannot be completed, it still returns a value:',
}

/**
 * Build the sample block for one README.
 *
 * @param file - the README file name, which selects the lead-in language.
 * @returns the block that belongs between the two markers.
 */
async function buildBlock(file) {
  const { renderRanked } = await loadPackageFile('lib/render.js')
  const card = renderRanked(IDEA, ROWS, [], [], [], [], NOISE, 'scout_projects')

  // The refused card, from the tool itself. The fake context exposes neither
  // `llm` nor a token, so a Chinese idea with no Latin keywords crosses the
  // refusal path before a single request is made.
  const plugin = await loadPlugin()
  const { ctx, tools } = fakeContext()
  plugin.apply(ctx)
  const scout = tools.get('scout_projects')
  if (scout === undefined) throw new Error('scout_projects did not register')

  const refused = await scout.execute({ idea: REFUSED_IDEA }, {})
  if (refused.degraded?.reason !== 'plan_failed') {
    throw new Error(
      `The refusal sample expected plan_failed, got ${JSON.stringify(refused.degraded)}. ` +
        'Either the refusal path changed or the context now exposes something it should not.',
    )
  }

  // The tool returns the degraded record; the card around it is what
  // `renderCandidates` prints for an empty, failed search. Composed here from
  // the same three pieces the tool would render, so the sample stays a faithful
  // picture of what a caller sees.
  const degraded = [
    `🎯 检索 idea："${REFUSED_IDEA}"`,
    '',
    '检索失败，无候选项目。',
    '',
    refused.degraded.detail,
  ].join('\n')

  return [
    '```',
    card,
    '```',
    '',
    REFUSAL_LEAD[file],
    '',
    '```',
    degraded,
    '```',
  ].join('\n')
}

/**
 * Splice a block into one README, or report that it is already current.
 *
 * @param file - README file name, relative to the package root.
 * @param block - the sample block.
 * @param write - `false` to compare only.
 * @returns `current`, `updated`, `stale`, or `skipped` when the README has no
 *   markers and therefore carries no generated sample.
 */
function splice(file, block, write) {
  const path = join(pkgRoot, file)
  const text = readFileSync(path, 'utf8')
  const from = text.indexOf(START)
  const to = text.indexOf(END)
  if (from === -1 || to === -1 || to < from) return 'skipped'
  const head = text.slice(0, from + START.length)
  const tail = text.slice(to)
  const current = text.slice(from + START.length, to)

  // Compare with line endings normalised. `core.autocrlf=true` checks these
  // files out as CRLF on Windows, and a byte comparison against the
  // generator's LF block would then report every sample stale on a machine
  // where nothing changed — a false alarm that trains the reader to ignore
  // the check. The block is written back in whatever ending the file uses.
  const eol = text.includes('\r\n') ? '\r\n' : '\n'
  const normalised = current.replaceAll('\r\n', '\n')

  if (normalised.includes(PLACEHOLDER) || normalised !== `\n${block}\n`) {
    if (!write) return 'stale'
    const spliced = `${head}\n${block}\n${tail}`.replaceAll('\r\n', '\n')
    writeFileSync(path, spliced.replaceAll('\n', eol), 'utf8')
    return 'updated'
  }
  return 'current'
}

const check = process.argv.includes('--check')
const files = Object.keys(REFUSAL_LEAD)

let stale = 0
let skipped = 0
for (const file of files) {
  // A README with no markers is checked for nothing, so the block is not even
  // generated: building it would only assert the generator still runs.
  const hasMarkers = readFileSync(join(pkgRoot, file), 'utf8').includes(START)
  const outcome = hasMarkers ? splice(file, await buildBlock(file), !check) : 'skipped'
  if (outcome === 'stale') stale++
  if (outcome === 'skipped') skipped++
  console.log(`${file}: ${outcome}${outcome === 'stale' ? ' — run "npm run readme:sample"' : ''}`)
}

if (check && stale > 0) {
  console.log(`\n${stale} README sample(s) no longer match the code.`)
  process.exit(1)
}
if (skipped > 0) {
  console.log(`\n${skipped} README(s) carry no sample markers, so nothing was checked there.`)
  console.log('README samples are current where they exist.')
} else {
  console.log(check ? '\nREADME samples are current.' : '\nREADME samples regenerated.')
}
